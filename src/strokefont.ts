type Stroke = [number, number][];
const parsed = new Map<string, Stroke[]>();

/** 모르는 글자: 빈 상자 */
const BOX: Stroke[] = [
  [
    [0.5, 0],
    [3.5, 0],
    [3.5, 6],
    [0.5, 6],
    [0.5, 0],
  ],
];

/** 글자 하나의 꺾은선(글자 칸 좌표) */
export function glyph(ch: string): Stroke[] {
  const hit = parsed.get(ch);
  if (hit) return hit;
  let def = DEF[ch];
  let scale = 1;
  if (def === undefined && ch !== ch.toUpperCase() && DEF[ch.toUpperCase()] !== undefined) {
    def = DEF[ch.toUpperCase()];
    scale = 0.75;
  }
  const out: Stroke[] =
    def === undefined
      ? BOX
      : def
          .split(';')
          .filter(Boolean)
          .map((pl) => pl.trim().split(/\s+/).map((pt) => pt.split(',').map((v) => Number(v) * scale) as [number, number]));
  parsed.set(ch, out);
  return out;
}

/** 아는 글자인지(빈 상자로 그리지 않는) */
export function hasGlyph(ch: string): boolean {
  return ch === ' ' || DEF[ch] !== undefined || DEF[ch.toUpperCase()] !== undefined;
}

export interface TextLayout {
  /** 2D 선분 쌍 x0,y0,x1,y1,…(글자 높이 단위, 기준선 왼쪽 = 0,0) */
  segs: number[];
  /** 글줄 너비(글자 높이 단위) */
  width: number;
}

/** 글 → 2D 선분(높이 1 = 대문자 높이, 여러 줄은 아래로 1.6씩) */
export function layoutText(text: string): TextLayout {
  const k = 1 / 6;
  const segs: number[] = [];
  let width = 0;
  text.split(/\r?\n/).forEach((line, li) => {
    let x = 0;
    const y0 = -li * 1.6;
    for (const ch of line) {
      for (const st of glyph(ch))
        for (let i = 1; i < st.length; i++) segs.push((x + st[i - 1]![0]) * k, y0 + st[i - 1]![1] * k, (x + st[i]![0]) * k, y0 + st[i]![1] * k);
      x += 5;
    }
    width = Math.max(width, Math.max(0, x - 1) * k);
  });
  return { segs, width };
}
